-- 社区药箱过期药回收服务 - 初始 schema
-- 兼容 PostgreSQL 15 与 H2(PostgreSQL 模式，用于测试)

CREATE TABLE community_points (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                     VARCHAR(100) NOT NULL,
    address                  VARCHAR(255),
    pickup_threshold_grams   INT NOT NULL DEFAULT 50000,
    created_at               TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username            VARCHAR(64)  NOT NULL UNIQUE,
    password_hash       VARCHAR(100) NOT NULL,
    name                VARCHAR(64)  NOT NULL,
    phone               VARCHAR(32),
    role                VARCHAR(20)  NOT NULL,           -- RESIDENT / COLLECTOR / ADMIN
    community_point_id  BIGINT REFERENCES community_points(id),
    created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE points_rules (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category        VARCHAR(20) NOT NULL UNIQUE,          -- TABLET/ANTIBIOTIC/PSYCHOTROPIC/SYRINGE/EXTERNAL/LIQUID
    points_per_gram NUMERIC(10,4) NOT NULL,
    description     VARCHAR(255),
    enabled         BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE activity_days (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_point_id  BIGINT NOT NULL REFERENCES community_points(id),
    name                VARCHAR(100) NOT NULL,
    activity_date       DATE NOT NULL,
    created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE appointments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_no      VARCHAR(32) NOT NULL UNIQUE,
    resident_id         BIGINT NOT NULL REFERENCES users(id),
    community_point_id  BIGINT NOT NULL REFERENCES community_points(id),
    activity_day_id     BIGINT REFERENCES activity_days(id),
    drug_type           VARCHAR(100) NOT NULL,
    quantity            INT NOT NULL,
    has_prescription    BOOLEAN NOT NULL DEFAULT FALSE,   -- 是否含处方药
    is_liquid           BOOLEAN NOT NULL DEFAULT FALSE,   -- 是否液体
    is_injection        BOOLEAN NOT NULL DEFAULT FALSE,   -- 是否针剂
    has_personal_info   BOOLEAN NOT NULL DEFAULT FALSE,   -- 是否有个人信息包装
    note                VARCHAR(500),
    status              VARCHAR(20) NOT NULL DEFAULT 'PENDING',  -- PENDING/CHECKED_IN/COMPLETED/CANCELLED
    created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    checked_in_at       TIMESTAMP
);

CREATE TABLE recycle_batches (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no            VARCHAR(32) NOT NULL UNIQUE,
    community_point_id  BIGINT NOT NULL REFERENCES community_points(id),
    collector_id        BIGINT NOT NULL REFERENCES users(id),
    activity_day_id     BIGINT REFERENCES activity_days(id),
    status              VARCHAR(20) NOT NULL DEFAULT 'OPEN',     -- OPEN/IN_STORAGE/HANDED_OVER
    created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at           TIMESTAMP
);

CREATE TABLE storage_cabinets (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_point_id  BIGINT NOT NULL REFERENCES community_points(id),
    code                VARCHAR(50) NOT NULL UNIQUE,
    capacity_bags       INT NOT NULL,
    created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE handovers (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handover_no           VARCHAR(32) NOT NULL UNIQUE,
    community_point_id    BIGINT NOT NULL REFERENCES community_points(id),
    env_company           VARCHAR(100) NOT NULL,                  -- 去向：环保公司
    total_weight_grams    INT NOT NULL DEFAULT 0,
    bag_count             INT NOT NULL DEFAULT 0,
    photo_urls            VARCHAR(2000),
    receiver_name         VARCHAR(64),                            -- 签收人
    second_receiver_name  VARCHAR(64),                            -- 双人交接第二签收人
    dual_required         BOOLEAN NOT NULL DEFAULT FALSE,         -- 是否需要双人交接
    status                VARCHAR(20) NOT NULL DEFAULT 'DRAFT',   -- DRAFT/COMPLETED
    handed_by             BIGINT NOT NULL REFERENCES users(id),
    created_at            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at          TIMESTAMP
);

CREATE TABLE weigh_records (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id        BIGINT NOT NULL REFERENCES recycle_batches(id),
    appointment_id  BIGINT NOT NULL REFERENCES appointments(id),
    category        VARCHAR(20) NOT NULL,
    weight_grams    INT NOT NULL,
    photo_urls      VARCHAR(2000),                                -- 包装照片，逗号分隔
    seal_bag_no     VARCHAR(64) NOT NULL,                         -- 封袋编号
    weighed_by      BIGINT NOT NULL REFERENCES users(id),
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE sealed_bags (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seal_bag_no     VARCHAR(64) NOT NULL UNIQUE,                  -- 封袋编号
    batch_id        BIGINT NOT NULL REFERENCES recycle_batches(id),
    appointment_id  BIGINT NOT NULL REFERENCES appointments(id),  -- 来源预约（追溯）
    category        VARCHAR(20) NOT NULL,                         -- 分类
    weight_grams    INT NOT NULL,
    photo_urls      VARCHAR(2000),
    status          VARCHAR(20) NOT NULL DEFAULT 'SEALED',        -- SEALED/REVIEW_HOLD/STORED/HANDED_OVER/REJECTED
    cabinet_id      BIGINT REFERENCES storage_cabinets(id),
    stored_at       TIMESTAMP,
    handover_id     BIGINT REFERENCES handovers(id),
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE review_tickets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id    BIGINT NOT NULL REFERENCES recycle_batches(id),
    bag_id      BIGINT NOT NULL REFERENCES sealed_bags(id),
    category    VARCHAR(20) NOT NULL,
    reason      VARCHAR(255) NOT NULL,
    status      VARCHAR(20) NOT NULL DEFAULT 'PENDING',           -- PENDING/APPROVED/REJECTED
    reviewer_id BIGINT REFERENCES users(id),
    comment     VARCHAR(500),
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_at  TIMESTAMP
);

CREATE TABLE points_accounts (
    user_id     BIGINT PRIMARY KEY REFERENCES users(id),
    balance     INT NOT NULL DEFAULT 0,
    updated_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE points_transactions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id),
    batch_id    BIGINT,
    ref_type    VARCHAR(20) NOT NULL,                             -- EARN_WEIGH/EARN_REVIEW/REDEEM/ADJUST
    ref_id      BIGINT,
    points      INT NOT NULL,                                     -- 正为入账，负为扣减
    status      VARCHAR(20) NOT NULL,                             -- SUCCESS/FAILED/PENDING
    remark      VARCHAR(255),
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE exchange_orders (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id),
    item        VARCHAR(100) NOT NULL,
    points      INT NOT NULL,
    status      VARCHAR(20) NOT NULL,                             -- SUCCESS/FAILED
    fail_reason VARCHAR(255),
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE handover_bags (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handover_id BIGINT NOT NULL REFERENCES handovers(id),
    bag_id      BIGINT NOT NULL REFERENCES sealed_bags(id),
    UNIQUE (handover_id, bag_id)
);

CREATE TABLE exception_records (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id          BIGINT,
    appointment_id    BIGINT,
    bag_id            BIGINT,
    exchange_order_id BIGINT,
    type              VARCHAR(40) NOT NULL,  -- UNEXPIRED_DRUG/PRESCRIPTION_INFO_EXPOSED/UNSAFE_INJECTION/LIQUID_LEAK/WEIGHT_DISPUTE/POINTS_EXCHANGE_FAILED/ENV_REJECT/REVIEW_REJECTED/GENERAL
    description       VARCHAR(1000),
    status            VARCHAR(20) NOT NULL DEFAULT 'OPEN',        -- OPEN/RESOLVED
    handled_by        BIGINT,
    resolution        VARCHAR(500),
    created_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at       TIMESTAMP
);

CREATE INDEX idx_bags_batch   ON sealed_bags(batch_id);
CREATE INDEX idx_bags_status  ON sealed_bags(status);
CREATE INDEX idx_bags_cabinet ON sealed_bags(cabinet_id);
CREATE INDEX idx_appt_resident ON appointments(resident_id);
CREATE INDEX idx_appt_point    ON appointments(community_point_id);
CREATE INDEX idx_txn_user      ON points_transactions(user_id);
CREATE INDEX idx_exc_batch     ON exception_records(batch_id);
CREATE INDEX idx_exc_status    ON exception_records(status);
CREATE INDEX idx_weigh_batch   ON weigh_records(batch_id);
